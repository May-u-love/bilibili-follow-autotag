/**
 * 分类：名称+签名+认证描述+机构认证
 * @param {{uname:string, sign:string, verifyType:number, verifyDesc:string}} user
 * @returns {string|null} 分组名或null
 */
export function classifyByNameAndSign(user) {
  const uname = user.uname || "";
  const sign = user.sign || "";
  const desc = user.verifyDesc || "";

  // 1. 个人认证描述（高精度信号；规则可为正则或 (user)=>组名|null 条件函数）
  if (desc) {
    for (const [group, re] of CERT_RULES) {
      if (!re.test(desc)) continue;
      const g = typeof group === "function" ? group(user) : group;
      if (g) return g;
    }
  }

  // 2. 机构认证：汽车/游戏官方账号归对应领域，其余归官方媒体与品牌
  if (user.verifyType === 1) {
    const orgText = `${uname} ${sign}`;
    if (/汽车|车|新能源|电动|出行|极氪|领克|奕派/i.test(orgText)) return "汽车与出行";
    if (/电竞|俱乐部|战队|游戏赛事|英雄联盟赛事|足球赛事/i.test(orgText)) return "游戏与电竞";
    return "官方媒体与品牌";
  }

  // 3. 名称+签名关键词（规则可为正则或 (user)=>组名|null 条件函数）
  const text = `${uname} ${sign}`;
  if (text.trim()) {
    for (const [group, re] of NAME_RULES) {
      if (!re.test(text)) continue;
      const g = typeof group === "function" ? group(user) : group;
      if (g) return g;
    }
  }
  return null;
}

