export function classifyByTitles(titles) {
  if (!titles || titles.length === 0) return null;
  const scores = {};
  for (const [group, re] of TITLE_RULES) {
    let n = 0;
    for (const t of titles) if (t && re.test(t)) n++;
    if (n > 0) scores[group] = n;
  }
  const sorted = Object.entries(scores).sort((a, b) => b[1] - a[1]);
  if (sorted.length && sorted[0][1] >= 2 && sorted[0][1] >= (sorted[1]?.[1] || 0) * 2) {
    return sorted[0][0];
  }
  return null;
}
